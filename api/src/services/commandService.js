const connect = require("../database/connect");
const createLog = require("../utils/createLog");

const crypto = require("crypto");

module.exports = class CommandService {
  static async createCommandByQr(token, customer_name) {
    const connection = await connect.getConnection();

    try {
      await connection.beginTransaction();

      // Resolve the QR Code and its table using the transaction connection.
      // FOR UPDATE avoids a race with the QR Code being deactivated while
      // the command is being opened.
      const qrQuery = `
        SELECT
          qr.qr_code_id,
          qr.table_id,
          qr.position,
          tbl.number
        FROM qr_codes qr
        INNER JOIN tables tbl ON tbl.table_id = qr.table_id
        WHERE qr.token = ?
          AND qr.is_active = 1
          AND tbl.is_active = 1
        LIMIT 1
        FOR UPDATE
      `;

      const [qrResult] = await connection.execute(qrQuery, [token]);

      if (qrResult.length === 0) {
        throw {
          status: 404,
          message: "QR Code não encontrado.",
        };
      }

      const qr = qrResult[0];

      // The session token is always generated by the backend.
      const session_token = crypto.randomUUID();

      const createQuery = `
        INSERT INTO commands
          (customer_name, session_token, status, table_id, qr_code_id, opened_by)
        VALUES (?, ?, 'OPEN', ?, ?, NULL)
      `;

      const [result] = await connection.execute(createQuery, [
        customer_name,
        session_token,
        qr.table_id,
        qr.qr_code_id,
      ]);

      const command_id = result.insertId;

      await createLog(
        connection,
        null,
        "INSERT",
        "commands",
        command_id,
        `Cliente ${customer_name} abriu a comanda #${command_id} da mesa #${qr.number}.`,
      );

      await connection.commit();

      return {
        message: "Comanda aberta com sucesso.",
        command_id,
        session_token,
        status: "OPEN",
        table_id: qr.table_id,
        qr_code_id: qr.qr_code_id,
      };
    } catch (error) {
      await connection.rollback();

      if (error.status) {
        throw error;
      }

      throw {
        status: 500,
        message: "Erro ao abrir a comanda.",
      };
    } finally {
      connection.release();
    }
  }
};
