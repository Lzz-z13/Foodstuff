const connect = require("../database/connect");
const createLog = require("../utils/createLog");

module.exports = class TableService {
  static async createTable(number, jwt_user_id) {
    const connection = await connect.getConnection();
    try {
      await connection.beginTransaction();

      const consultQuery = `SELECT name FROM users WHERE user_id = ? AND is_active = 1 LIMIT 1`;
      const [userResult] = await connection.execute(consultQuery, [jwt_user_id]);
      const user_name = userResult[0].name;

      const createQuery = `INSERT INTO tables (number) VALUE (?)`;
      const [result] = await connection.execute(createQuery, [number]);
      const newCourseId = result.insertId; // Grab the ID generated by the AUTO_INCREMENT

      await createLog(connection, jwt_user_id, 'INSERT', 'tables', newCourseId, `Usuário ${user_name} criou a mesa #${number}` );

      await connection.commit();
      return newCourseId;
    } catch (error) {
      await connection.rollback();
      throw { status: 500, message: "Erro ao criar a mesa." };
    } finally {
      connection.release();
    }
  }

    static async readAllTables() {
    const query = `
      SELECT
        table_id,
        number
      FROM tables
      WHERE is_active = 1
    `;

    try {
      const [tables] = await connect.execute(query);
      return tables;
    } catch (error) {
      throw { status: 500, message: "Erro ao buscar as mesas do ativas." };
    }
  }
}